function [T, outPaths] = makeSupplementaryStatsTable(params)
% makeSupplementaryStatsTable  Generate the supplementary statistics table.
%
%   [T, outPaths] = makeSupplementaryStatsTable()
%   [T, outPaths] = makeSupplementaryStatsTable(nBootPval = 1e5, ...)
%
%   Thin driver over buildStatsTable holding the comparison -> figure mapping.
%   Edit the SPEC below to control exactly what appears in the table; nothing
%   else needs changing.
%
%   ##################  READ BEFORE PUBLISHING  ##########################
%   The figure labels below were inferred from the Paper_figs FOLDER NAMES,
%   not from the manuscript. Two things need your eyes:
%
%   (1) DUPLICATED COMPARISONS. Several analyses are saved under two figure
%       folders. Where the two files are byte-identical copies the duplicate
%       is commented out here; where they differ (regenerated at different
%       times) BOTH are listed and you must decide which is authoritative:
%         - SDGm vs SDGs (49-97)      : Figure 3 and Figure S3, identical file
%         - SDGm x SDGs angles        : Figure 3 and Figure S3, identical file
%         - NI vs NV                  : Figure 3 and Figure S3, DIFFERENT files
%         - MB-MBR / MB-SDGm / MB-MBR-SDGm : Figure 4 and Figure S4, DIFFERENT
%           files (the Figure 4 copies are newer)
%
%   (2) PAIR SELECTION for the two 8-condition analyses. Their full pairwise
%       matrix is 28 comparisons each, which would swamp the table. They are
%       restricted below to the MATCHED cross-stimulus pairs (same angle or
%       direction in each stimulus), which is the comparison those panels are
%       built around. If the figure brackets a different subset, edit the
%       pair list. Set the third column to "all" to restore the full matrix.
%   ######################################################################
%
%   See also: buildStatsTable, AllExpAnalysis

arguments
    params.root        char    = 'W:\Large_scale_mapping_NP\Paper_figs\'
    params.outDir      char    = 'W:\Large_scale_mapping_NP\Paper_figs\'
    params.outName     char    = 'SupplementaryStatsTable'
    params.nBootPval   double  = 1e5
    params.pvalSeed    double  = 0
    params.write       logical = true
    params.include     cell    = {'Fig 1'}   % which SPEC rows to run, matched as
                                             %   substrings of the figure label.
                                             %   Default: the MB vs SB comparison
                                             %   only (3 rows: Z-score, SpkR,
                                             %   FracResponsive). Widen when you
                                             %   want other stimuli, e.g.
                                             %   include = {'Fig 1','Fig 3'}, or
                                             %   {} for every comparison below.
end

R = params.root;

% Matched cross-stimulus pairs for the two 8-condition analyses (see note 2)
anglePairs = { ...
    'SDGm_ang_0',    'SDGs_ang_0'; ...
    'SDGm_ang_1.57', 'SDGs_ang_1.57'; ...
    'SDGm_ang_3.14', 'SDGs_ang_3.14'; ...
    'SDGm_ang_4.71', 'SDGs_ang_4.71'};

% MB direction vs MG angle. CAREFUL: this struct stores the SDGm angles in
% DEGREES (its labels were never rewritten by AllExpAnalysis SECTION 7, unlike
% the Figure 3/5 structs), while MB directions are in radians. The pairs below
% are therefore matched by DIRECTION, not by matching numbers, using SECTION
% 7's own conversion:  0 deg -> 1.57 rad,  90 -> 0,  180 -> 4.71,  270 -> 3.14.
% CONFIRM this is the pairing the panel shows before publishing.
dirAnglePairs = { ...
    'MB_dir_0',    'SDGm_ang_90'; ...    % 0    rad  <->  90 deg
    'MB_dir_1p57', 'SDGm_ang_0'; ...     % 1.57 rad  <->   0 deg
    'MB_dir_3p14', 'SDGm_ang_270'; ...   % 3.14 rad  <-> 270 deg
    'MB_dir_4p71', 'SDGm_ang_180'};      % 4.71 rad  <-> 180 deg

% ---------------------------------------------------------------------
% SPEC: {figure label, struct file, pairs}
% ---------------------------------------------------------------------
SPEC = { ...
% --- Figure 1 -------------------------------------------------------------
% Root copy: the one AllExpAnalysis writes on each run, i.e. the current
% analysis. The older copy under 'Figure 1 No FDR _general result\' is a
% five-day-old snapshot; its TableRespNeurs is identical but do not assume the
% same of TableStimComp.
'Fig 1  MB vs SB', ...
    [R 'Ex_1-97_Combined_MB-RG_analysisStruct.mat'], "all"; ...

% --- Figure 3 -------------------------------------------------------------
'Fig 3  NV vs NI', ...
    [R 'Figure 3 _ Moving vs static global stim\Ex_40-97_Combined_NV-NI_analysisStruct.mat'], "all"; ...
'Fig 3  MG vs SG (Ex40-97)', ...
    [R 'Figure 3 _ Moving vs static global stim\Ex_40-97_Combined_SDGm-SDGs_analysisStruct.mat'], "all"; ...
'Fig 3  MG vs SG (Ex49-97)', ...
    [R 'Figure 3 _ Moving vs static global stim\Ex_49-97_Combined_SDGm-SDGs_analysisStruct.mat'], "all"; ...
'Fig 3  MG vs SG by angle', ...
    [R 'Figure 3 _ Moving vs static global stim\Ex_40-97_SpecLvl_SDGm-angles-0_90_180_270__SDGs-angles-0_90_180_270_analysisStruct.mat'], anglePairs; ...
'Fig 3  NI by image order vs NV', ...
    [R 'Figure 3 _ Moving vs static global stim\Ex_92-97_SpecLvl_NI-imgeOrder-1_9__NV_analysisStruct.mat'], "all"; ...

% --- Figure 4 -------------------------------------------------------------
'Fig 4  MB vs MBR', ...
    [R 'Figure 4 _ local vs global stimuli\Ex_40-97_Combined_MB-MBR_analysisStruct.mat'], "all"; ...
'Fig 4  MB vs MG', ...
    [R 'Figure 4 _ local vs global stimuli\Ex_40-97_Combined_MB-SDGm_analysisStruct.mat'], "all"; ...
'Fig 4  MB vs MBR vs MG', ...
    [R 'Figure 4 _ local vs global stimuli\Ex_49-97_Combined_MB-MBR-SDGm_analysisStruct.mat'], "all"; ...
'Fig 4  MB by size', ...
    [R 'Figure 4 _ local vs global stimuli\Ex_49-97_Combined_MB_sizes_analysisStruct.mat'], "all"; ...
'Fig 4  SB vs FFF', ...
    [R 'Figure 4 _ local vs global stimuli\Ex_49-97_Combined_RG-FFF_analysisStruct.mat'], "all"; ...
'Fig 4  SB vs SG', ...
    [R 'Figure 4 _ local vs global stimuli\Ex_49-97_Combined_RG-SDGs_analysisStruct.mat'], "all"; ...
'Fig 4  SB vs SG vs FFF', ...
    [R 'Figure 4 _ local vs global stimuli\Ex_49-97_Combined_RG-SDGs-FFF_analysisStruct.mat'], "all"; ...

% --- Figure 5 -------------------------------------------------------------
'Fig 5  MB by direction', ...
    [R 'Figure 5 _ direction analysis\Ex_40-97_Combined_MB_directions_analysisStruct.mat'], "all"; ...
'Fig 5  MG by angle', ...
    [R 'Figure 5 _ direction analysis\Ex_40-97_SpecLvl_SDGm-angles-0_90_180_270_analysisStruct.mat'], "all"; ...

% --- Figure S1 ------------------------------------------------------------
'Fig S1 MB vs SB (300 ms onset)', ...
    [R 'Figure S1\Ex_1-97_Combined_MB-RG_analysisStruct_300msOnset.mat'], "all"; ...

% --- Figure S3 ------------------------------------------------------------
% NOTE: the SDGm-SDGs and angle files here are byte-identical to the Figure 3
% copies, so they are omitted to avoid duplicate rows. The NI-NV file DIFFERS
% from the Figure 3 one and is therefore listed.
'Fig S3 NI by image order vs NV', ...
    [R 'Figure S3\Ex_92-97_SpecLvl_NI-imgeOrder-1_9__NV_analysisStruct.mat'], "all"; ...

% --- Figure S4 ------------------------------------------------------------
% NOTE: MB-MBR, MB-SDGm and MB-MBR-SDGm also exist under Figure 4 as NEWER
% files. Both are listed so you can compare; delete whichever is not the one
% in the manuscript.
'Fig S4 MB vs MBR (S4 copy)', ...
    [R 'Figure S4\Ex_49-97_Combined_MB-MBR_analysisStruct.mat'], "all"; ...
'Fig S4 MB vs MG (S4 copy)', ...
    [R 'Figure S4\Ex_49-97_Combined_MB-SDGm_analysisStruct.mat'], "all"; ...
'Fig S4 MB vs MBR vs MG (S4 copy)', ...
    [R 'Figure S4\Ex_49-97_Combined_MB-MBR-SDGm_analysisStruct.mat'], "all"; ...
'Fig S4 MG by spatial frequency', ...
    [R 'Figure S4\Ex_49-97_Combined_SDGm_spatfrequency_analysisStruct.mat'], "all"; ...
'Fig S4 SG by spatial frequency', ...
    [R 'Figure S4\Ex_49-97_Combined_SDGs_spatfrequency_analysisStruct.mat'], "all"; ...
'Fig S4 MB direction vs MG angle', ...
    [R 'Figure S4\Ex_49-97_SpecLvl_MB-directions-0_1.57_3.14_4.71__SDGm-angles-0_90_180_270_analysisStruct.mat'], dirAnglePairs; ...

% --- Figure S5 ------------------------------------------------------------
'Fig S5 MG by temporal frequency', ...
    [R 'Figure S5\Ex_49-97_Combined_SDGm_tempfrequency_analysisStruct.mat'], "all"; ...
};

% Restrict to the requested comparisons. The default is Figure 1 (MB vs SB)
% alone: that is the comparison the table was built to document, and running
% every entry below produces 156 rows, which is far more than a supplementary
% table supporting one claim needs. The rest are kept here so other stimuli can
% be added later without reconstructing the spec.
if ~isempty(params.include)
    keepInc = false(size(SPEC,1),1);
    for i = 1:numel(params.include)
        keepInc = keepInc | contains(string(SPEC(:,1)), string(params.include{i}));
    end
    assert(any(keepInc), ...
        'include = {%s} matched no entry. Available labels:\n  %s', ...
        strjoin(params.include, ', '), strjoin(string(SPEC(:,1))', '\n  '));
    SPEC = SPEC(keepInc, :);
end

% Drop any entry whose file is missing, with a loud warning, so one moved file
% does not abort the whole table.
keep = true(size(SPEC,1),1);
for i = 1:size(SPEC,1)
    if exist(SPEC{i,2}, 'file') ~= 2
        warning('makeSupplementaryStatsTable:missing', ...
            'Skipping "%s" - file not found:\n  %s', SPEC{i,1}, SPEC{i,2});
        keep(i) = false;
    end
end
SPEC = SPEC(keep, :);

[T, outPaths] = buildStatsTable(SPEC, ...
    outDir    = params.outDir, ...
    outName   = params.outName, ...
    nBootPval = params.nBootPval, ...
    pvalSeed  = params.pvalSeed, ...
    write     = params.write);

end
